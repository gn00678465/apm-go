package compile

import (
	"sort"
	"strings"
)

// SourcedInstruction pairs a ParsedInstruction with its display-relative
// source path (forward-slash, relative to the project root). RelPath is the
// deterministic within-group sort key (oracle: template_builder.py:67-68)
// and what the CLI lists as a compiled source; it is not written to the
// file.
type SourcedInstruction struct {
	RelPath string
	ParsedInstruction
}

const globalHeading = "## Global Instructions"

// generatedMarker is the ownership marker of the Oracle's default
// (distributed) compile (compilation/constants.py:24-26).
const generatedMarker = "<!-- Generated by APM CLI from distributed .apm/ primitives -->"

// buildIDPlaceholder is the sentinel line RenderAgentsMD emits in place of
// the real Build ID; StabilizeBuildID replaces it before the content is
// written to disk (oracle: compilation/constants.py BUILD_ID_PLACEHOLDER).
const buildIDPlaceholder = "<!-- Build ID: __BUILD_ID__ -->"

// RenderAgentsMD builds the root AGENTS.md content (still containing
// buildIDPlaceholder -- callers must run StabilizeBuildID before writing to
// disk) in the form the Oracle's default compile writes
// (distributed_compiler.py:714-751 with source_attribution off, its
// default: no APM Version line, no Source comments, no footer).
//
// Every instruction goes into this one file, also one with applyTo, which
// the Oracle may place in a sub-directory AGENTS.md (issue #50 ruling R11).
// Such a section has the form the Oracle gives a pattern group in whichever
// AGENTS.md it writes it to.
func RenderAgentsMD(instructions []SourcedInstruction) string {
	sections := []string{
		"# AGENTS.md",
		generatedMarker,
		buildIDPlaceholder,
		"",
	}
	sections = append(sections, renderInstructionsBlock(instructions)...)
	return strings.Join(sections, "\n")
}

// renderInstructionsBlock mirrors render_instructions_block
// (compilation/template_builder.py:25-92): global instructions (no applyTo)
// render first under one heading sorted by RelPath, then pattern-scoped
// groups sorted by pattern (the normalized applyTo string, never split on
// commas), each internally sorted by RelPath.
//
// A group's heading is emitted whenever at least one instruction belongs
// to it, even if every instruction in the group has an empty body: the
// Oracle's `if instruction.content.strip():` guards only the lines of the
// instruction itself.
func renderInstructionsBlock(instructions []SourcedInstruction) []string {
	var globals []SourcedInstruction
	patternGroups := make(map[string][]SourcedInstruction)
	var patterns []string
	for _, inst := range instructions {
		if inst.ApplyTo == "" {
			globals = append(globals, inst)
			continue
		}
		if _, ok := patternGroups[inst.ApplyTo]; !ok {
			patterns = append(patterns, inst.ApplyTo)
		}
		patternGroups[inst.ApplyTo] = append(patternGroups[inst.ApplyTo], inst)
	}
	sort.Strings(patterns)

	var sections []string
	if len(globals) > 0 {
		sections = append(sections, globalHeading, "")
		sections = append(sections, emitGroup(globals)...)
	}
	for _, pattern := range patterns {
		sections = append(sections, "## Files matching `"+pattern+"`", "")
		sections = append(sections, emitGroup(patternGroups[pattern])...)
	}
	return sections
}

// emitGroup sorts a group's instructions by RelPath and emits the body and
// a blank line for every member with a non-empty body (oracle:
// template_builder.py:122-130, the `_emit` closure with no source map).
func emitGroup(group []SourcedInstruction) []string {
	sorted := make([]SourcedInstruction, len(group))
	copy(sorted, group)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].RelPath < sorted[j].RelPath })

	var lines []string
	for _, inst := range sorted {
		if inst.Body == "" {
			continue
		}
		lines = append(lines, inst.Body, "")
	}
	return lines
}
