func inst(relPath, applyTo, body string) SourcedInstruction {
	return SourcedInstruction{
		RelPath:           relPath,
		ParsedInstruction: ParsedInstruction{ApplyTo: applyTo, Body: body},
	}
}

// The expected documents in this file are files the Oracle (v0.33.0) wrote
// with `apm compile`, default mode, target codex, read back byte for byte
// (issue #50, 2026-10-12). Their Build IDs are the Oracle's, so each test
// also pins the Build ID algorithm against a value the Go code did not
// compute.

// TestRender_OracleRootFile_GlobalOnly is the root AGENTS.md the Oracle
// writes for tools/parity/cases/compile-instruction/fixture as it was before
// issue #76.
func TestRender_OracleRootFile_GlobalOnly(t *testing.T) {
	instructions := []SourcedInstruction{
		inst(".apm/instructions/example.instructions.md", "", "# Example instruction\n\nUse the example."),
	}
	want := "# AGENTS.md\n" +
		"<!-- Generated by APM CLI from distributed .apm/ primitives -->\n" +
		"<!-- Build ID: 4ad235adde29 -->\n" +
		"\n" +
		"## Global Instructions\n" +
		"\n" +
		"# Example instruction\n" +
		"\n" +
		"Use the example.\n"
	if got := StabilizeBuildID(RenderAgentsMD(instructions)); got != want {
		t.Errorf("got:\n%q\nwant:\n%q", got, want)
	}
}

// TestRender_OracleRootFile_GlobalAndPatterns is a root AGENTS.md in which
// the Oracle itself placed pattern-scoped instructions (the matching files
// were spread over the root and several directories): two globals, a
// pattern group whose only member has an empty body (heading with nothing
// under it), a group with two members and one empty-body member, and a
// brace pattern kept as one heading. Input order is scrambled; the Oracle
// sorts globals first, then groups by pattern, then members by path.
func TestRender_OracleRootFile_GlobalAndPatterns(t *testing.T) {
	instructions := []SourcedInstruction{
		inst(".apm/instructions/zed.instructions.md", "", "# Zed global\n\nzed."),
		inst(".apm/instructions/ts.instructions.md", "**/*.{ts,tsx}", "TS rule."),
		inst(".apm/instructions/py.instructions.md", "**/*.py", "# Py rules\n\nUse py."),
		inst(".apm/instructions/onlyempty.instructions.md", "**/*.md", ""),
		inst(".apm/instructions/example.instructions.md", "", "# Example instruction\n\nUse the example."),
		inst(".apm/instructions/emptypy.instructions.md", "**/*.py", ""),
		inst(".apm/instructions/apy.instructions.md", "**/*.py", "# Another py\n\nMore py."),
	}
	want := "# AGENTS.md\n" +
		"<!-- Generated by APM CLI from distributed .apm/ primitives -->\n" +
		"<!-- Build ID: 852ef9f00cba -->\n" +
		"\n" +
		"## Global Instructions\n" +
		"\n" +
		"# Example instruction\n" +
		"\n" +
		"Use the example.\n" +
		"\n" +
		"# Zed global\n" +
		"\n" +
		"zed.\n" +
		"\n" +
		"## Files matching `**/*.md`\n" +
		"\n" +
		"## Files matching `**/*.py`\n" +
		"\n" +
		"# Another py\n" +
		"\n" +
		"More py.\n" +
		"\n" +
		"# Py rules\n" +
		"\n" +
		"Use py.\n" +
		"\n" +
		"## Files matching `**/*.{ts,tsx}`\n" +
		"\n" +
		"TS rule.\n"
	for i := 0; i < 25; i++ {
		if got := StabilizeBuildID(RenderAgentsMD(instructions)); got != want {
			t.Fatalf("iteration %d got:\n%q\nwant:\n%q", i, got, want)
		}
	}
}

