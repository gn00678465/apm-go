// TestRender_RawApplyToComma covers CMP-05: an applyTo value with an
// embedded comma produces exactly one heading, verbatim -- compile groups
// by the normalized applyTo string, never split on commas as install's
// .claude/rules paths are (oracle: template_builder.py:86 formats the dict
// key).
func TestRender_RawApplyToComma(t *testing.T) {
	got := RenderAgentsMD([]SourcedInstruction{
		inst(".apm/instructions/comma.instructions.md", "**/src/**, **/api/**", "Comma body."),
	})
	if strings.Count(got, "## Files matching") != 1 {
		t.Fatalf("expected exactly 1 heading, got content:\n%s", got)
	}
	if !strings.Contains(got, "## Files matching `**/src/**, **/api/**`\n\nComma body.\n") {
		t.Errorf("comma pattern not kept verbatim as one heading:\n%s", got)
	}
}

// TestRender_NoLegacyAnnotations: the Oracle's default mode has
// source_attribution off, so none of the `--single-agents` annotations
// (APM Version, Source / End source comments, footer) may appear, and the
// source path is not written anywhere.
func TestRender_NoLegacyAnnotations(t *testing.T) {
	got := StabilizeBuildID(RenderAgentsMD([]SourcedInstruction{
		inst(".apm/instructions/a.instructions.md", "", "Body."),
		inst("apm_modules/acme/dep/.apm/instructions/b.instructions.md", "**/*.go", "Go body."),
	}))
	for _, banned := range []string{
		"APM Version",
		"Source:",
		"End source",
		"---",
		"generated by APM CLI",
		"To regenerate",
		"a.instructions.md",
		"b.instructions.md",
		"from .apm/ primitives",
	} {
		if strings.Contains(got, banned) {
			t.Errorf("output must not contain %q:\n%s", banned, got)
		}
	}
}

// TestRender_UTF8LFAndTrailingNewline covers CMP-09: UTF-8 bytes survive
// round-trip, no CR anywhere in the output (documented LF deviation --
// design.md §4/§7; oracle writes CRLF on Windows, Go intentionally does
// not), and the file ends with exactly one trailing "\n".
func TestRender_UTF8LFAndTrailingNewline(t *testing.T) {
	instructions := []SourcedInstruction{
		inst(".apm/instructions/unicode.instructions.md", "", "中文內容 and émoji 🎉."),
	}
	got := StabilizeBuildID(RenderAgentsMD(instructions))

	if strings.ContainsRune(got, '\r') {
		t.Errorf("output must not contain any CR byte:\n%q", got)
	}
	if !strings.HasSuffix(got, "\n中文內容 and émoji 🎉.\n") {
		t.Errorf("UTF-8 body not preserved verbatim as the last line:\n%q", got)
	}
}

// TestBuildID_Stabilize covers CMP-10 beyond the Oracle documents above:
// the placeholder line is replaced, a second pass is a no-op, a changed
// body changes the ID, and content with no placeholder is returned as is.
func TestBuildID_Stabilize(t *testing.T) {
	content := "# AGENTS.md\n" + generatedMarker + "\n" + buildIDPlaceholder +
		"\n\n## Global Instructions\n\n# Example instruction\n\nUse the example.\n"

	got := StabilizeBuildID(content)
	want := strings.Replace(content, buildIDPlaceholder, "<!-- Build ID: 4ad235adde29 -->", 1)
	if got != want {
		t.Fatalf("got:\n%q\nwant:\n%q", got, want)
	}
	if again := StabilizeBuildID(got); again != got {
		t.Errorf("re-stabilizing changed content:\nfirst:  %q\nsecond: %q", got, again)
	}

	changed := StabilizeBuildID(strings.Replace(content, "Use the example.", "Use another.", 1))
	if strings.Contains(changed, "4ad235adde29") {
		t.Errorf("changed body did not change Build ID:\n%s", changed)
	}

	noPlaceholder := "# AGENTS.md\nno placeholder here\n"
	if out := StabilizeBuildID(noPlaceholder); out != noPlaceholder {
		t.Errorf("content without placeholder must be returned unchanged, got %q", out)
	}
}
