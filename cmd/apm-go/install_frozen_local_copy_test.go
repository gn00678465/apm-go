// Issue #128 (新-114-1): a frozen install copies each local package that has
// no copy in apm_modules/, also when every deployed file is on disk, as
// Oracle 0.33.0 does (~/.cache/apm-go-verify/issue128/r2, r3).

const (
	frozenCopyInstruction = "---\napplyTo: \"**/*.go\"\n---\nUse gofmt.\n"
	frozenCopyAgent       = "---\nname: a\ndescription: d\n---\nAgent body.\n"
	// frozenCopyOracleAgentsMD is what Oracle 0.33.0's compile wrote after its
	// frozen install copied the package back (r3/w-main-r-oracle/3-AGENTS.md).
	frozenCopyOracleAgentsMD = "# AGENTS.md\n<!-- Generated by APM CLI from distributed .apm/ primitives -->\n<!-- Build ID: 7c43993c6c84 -->\n\n## Files matching `**/*.go`\n\nUse gofmt.\n"
)

// frozenCopyProject installs ./repo, declared under section, and returns the
// project directory.
func frozenCopyProject(t *testing.T, section string) string {
	t.Helper()
	t.Setenv("APM_CONFIG_DIR", t.TempDir())
	project := chdirTemp(t)
	writeGlobalStaleFile(t, filepath.Join(project, "apm.yml"), "name: proj\nversion: 1.0.0\ntargets: [claude, codex]\n"+section+":\n  apm:\n  - ./repo\n")
	writeGlobalStaleFile(t, filepath.Join(project, "repo", "apm.yml"), "name: repo\nversion: 2.0.0\n")
	writeGlobalStaleFile(t, filepath.Join(project, "repo", ".apm", "instructions", "r.instructions.md"), frozenCopyInstruction)
	writeGlobalStaleFile(t, filepath.Join(project, "repo", ".apm", "agents", "a.agent.md"), frozenCopyAgent)
	if err := frozenCopyInstall(t, false); err != nil {
		t.Fatalf("install: %v", err)
	}
	return project
}

func frozenCopyInstall(t *testing.T, frozen bool) error {
	t.Helper()
	var err error
	captureUninstallStdout(t, func() {
		err = runInstall(&installDeps{tags: &mockInstallTagLister{}, loader: localOnlyLoader{t}}, frozen, true, "", "", nil, nil)
	})
	return err
}

// frozenCopySnapshot reads every file of the project outside apm_modules/,
// .git/ and the package source.
func frozenCopySnapshot(t *testing.T, project string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.WalkDir(project, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(project, path)
		if d.IsDir() {
			switch rel {
			case "apm_modules", "repo", "repo.gone", ".git":
				return filepath.SkipDir
			}
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[filepath.ToSlash(rel)] = string(data)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func assertSnapshot(t *testing.T, project string, want map[string]string) {
	t.Helper()
	got := frozenCopySnapshot(t, project)
	for rel, content := range want {
		if got[rel] != content {
			t.Errorf("%s changed:\n%q\nwant:\n%q", rel, got[rel], content)
		}
	}
	for rel := range got {
		if _, ok := want[rel]; !ok {
			t.Errorf("%s written", rel)
		}
	}
}

func assertNoLocalModules(t *testing.T, project string) {
	t.Helper()
	if _, err := os.Stat(filepath.Join(project, "apm_modules", "_local")); !os.IsNotExist(err) {
		t.Errorf("apm_modules/_local exists (err %v)", err)
	}
}

func TestInstall_Frozen_CopiesMissingLocalPackage(t *testing.T) {
	for _, tc := range []struct {
		name string
		ci   bool
	}{{"--frozen", false}, {"CI=1", true}} {
		t.Run(tc.name, func(t *testing.T) {
			project := frozenCopyProject(t, "dependencies")
			before := frozenCopySnapshot(t, project)
			if err := os.RemoveAll(filepath.Join(project, "apm_modules")); err != nil {
				t.Fatal(err)
			}
			if tc.ci {
				t.Setenv("CI", "1")
			}

			if err := frozenCopyInstall(t, !tc.ci); err != nil {
				t.Fatalf("frozen install: %v", err)
			}

			copied := filepath.Join(project, "apm_modules", "_local", "repo", ".apm", "instructions", "r.instructions.md")
			if _, err := os.Stat(copied); err != nil {
				t.Fatalf("local package not copied back: %v", err)
			}
			if got := globalStaleRead(t, copied); got != frozenCopyInstruction {
				t.Errorf("copied instruction = %q", got)
			}
			assertSnapshot(t, project, before)

			t.Setenv("CI", "")
			var err error
			captureUninstallStdout(t, func() { err = runCompile("codex", project) })
			if err != nil {
				t.Fatalf("compile: %v", err)
			}
			if got := globalStaleRead(t, filepath.Join(project, "AGENTS.md")); got != frozenCopyOracleAgentsMD {
				t.Errorf("AGENTS.md:\n%s\nwant:\n%s", got, frozenCopyOracleAgentsMD)
			}
			out := captureUninstallStdout(t, func() { err = runUninstall([]string{"./repo"}, uninstallOptions{}) })
			if err != nil {
				t.Fatalf("uninstall: %v\n%s", err, out)
			}
			if strings.Contains(out, "not found in apm_modules") {
				t.Errorf("uninstall output:\n%s", out)
			}
		})
	}
}

func TestInstall_Frozen_CopiesMissingLocalDevPackage(t *testing.T) {
	project := frozenCopyProject(t, "devDependencies")
	before := frozenCopySnapshot(t, project)
	if err := os.RemoveAll(filepath.Join(project, "apm_modules")); err != nil {
		t.Fatal(err)
	}

	if err := frozenCopyInstall(t, true); err != nil {
		t.Fatalf("frozen install: %v", err)
	}

	if got := globalStaleRead(t, filepath.Join(project, "apm_modules", "_local", "repo", ".apm", "agents", "a.agent.md")); got != frozenCopyAgent {
		t.Errorf("copied agent = %q", got)
	}
	assertSnapshot(t, project, before)
}

// Oracle 0.33.0 ends with exit 1 when the source is gone (r2/srcgone-oracle).
func TestInstall_Frozen_MissingLocalSourceFails(t *testing.T) {
	project := frozenCopyProject(t, "dependencies")
	before := frozenCopySnapshot(t, project)
	if err := os.RemoveAll(filepath.Join(project, "apm_modules")); err != nil {
		t.Fatal(err)
	}
	if err := os.Rename(filepath.Join(project, "repo"), filepath.Join(project, "repo.gone")); err != nil {
		t.Fatal(err)
	}

	err := frozenCopyInstall(t, true)

	if err == nil || !strings.Contains(err.Error(), "frozen install: copy local package ./repo: ") {
		t.Fatalf("frozen install error = %v", err)
	}
	if code := exitCodeOf(err); code != 1 {
		t.Errorf("exit code %d, want 1", code)
	}
	assertNoLocalModules(t, project)
	assertSnapshot(t, project, before)
}

// A copy that is there is kept, so a source that is gone is not read.
func TestInstall_Frozen_KeepsExistingLocalCopy(t *testing.T) {
	project := frozenCopyProject(t, "dependencies")
	before := frozenCopySnapshot(t, project)
	if err := os.Rename(filepath.Join(project, "repo"), filepath.Join(project, "repo.gone")); err != nil {
		t.Fatal(err)
	}

	if err := frozenCopyInstall(t, true); err != nil {
		t.Fatalf("frozen install: %v", err)
	}

	if got := globalStaleRead(t, filepath.Join(project, "apm_modules", "_local", "repo", ".apm", "agents", "a.agent.md")); got != frozenCopyAgent {
		t.Errorf("kept agent = %q", got)
	}
	assertSnapshot(t, project, before)
}

// A changed deployed file is reported before any copy.
func TestInstall_Frozen_ChangedDeployedFileFailsBeforeCopy(t *testing.T) {
	project := frozenCopyProject(t, "dependencies")
	agent := filepath.Join(project, ".claude", "agents", "a.md")
	writeGlobalStaleFile(t, agent, "edited\n")
	before := frozenCopySnapshot(t, project)
	if err := os.RemoveAll(filepath.Join(project, "apm_modules")); err != nil {
		t.Fatal(err)
	}

	err := frozenCopyInstall(t, true)

	if err == nil || !strings.Contains(err.Error(), "content-integrity violation") {
		t.Fatalf("frozen install error = %v", err)
	}
	assertNoLocalModules(t, project)
	assertSnapshot(t, project, before)
}
